import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=path.join(root,'dist');
const data=(await fs.readFile(path.join(dir,'data.js'),'utf8')).replace('export const jobs =','const jobs =').replace('export const candidates =','const fixtures =');
const icons=(await fs.readFile(path.join(dir,'icons.js'),'utf8')).replaceAll('export const ','const ');
const main=(await fs.readFile(path.join(dir,'main.js'),'utf8')).replace(/^import .*;\r?\n/gm,'');
await fs.writeFile(path.join(dir,'bundle.js'),'/* Generated by scripts/build.mjs. Edit main.js, data.js or icons.js. */\n(()=>{\n'+data+'\n'+icons+'\n'+main+'\n})();\n');
console.log('Built browser bundle. The UI can run over HTTP or by opening dist/index.html.');
